#!/bin/bash
# Cross-build camel-lite (the mail library of Modest) with the OpenSSL backend and OpenSSL 3 for Maemo 5.
# Run INSIDE the Workshop:  make -C apps/camel-lite build   (needs: make -C apps/openssl build, libxml2-dev in the sysroot)
#
# Why: Modest talks to mail servers through camel-lite, which uses the NSS 3.12 of the browser (TLS 1.0 only).
# Servers such as Centrum require TLS 1.2. camel-lite has an OpenSSL backend too (camel-tcp-stream-openssl.c),
# written for OpenSSL 0.9.8; openssl3.patch ports it to OpenSSL 3, which is linked statically into libcamel-lite.
# Source: github.com/community-ssu/tinymail (CSSU branch of tinymail 1.1.92, the camel-lite of the device).
# Output: /project/build/out/camel-lite-$VERSION/root/usr/lib/... (installed tree, prefix /usr like the original library,
# because the provider directory is compiled in), root/opt/camel-lite3/bin/camel-tlstest
set -euo pipefail

VERSION="${VERSION:-1.1.92cssu7}"
COMMIT=80501e88bd95e1006c2c780a0cfaff2f68a6a802
SSLV="${SSLV:-3.5.9}"
PROJ=/project
SR="$PROJ/sysroot"
DL="$PROJ/build/downloads"
SRCDIR="$PROJ/build/src"
OUT="$PROJ/build/out/camel-lite-$VERSION"
SSLDEP="$PROJ/build/deps/openssl-$SSLV"

[ -d "$SR/usr/include/libxml2" ] || { echo "Missing libxml2-dev in the sysroot: python3 scripts/fetch_sysroot.py libxml2-dev"; exit 1; }
[ -s "$SSLDEP/lib/libssl.a" ] || { echo "Missing OpenSSL, run: make -C apps/openssl build"; exit 1; }
mkdir -p "$DL" "$SRCDIR"
f="tinymail-$COMMIT.tar.gz"
[ -s "$DL/$f" ] || curl -fL --retry 3 -o "$DL/$f" "https://github.com/community-ssu/tinymail/archive/$COMMIT.tar.gz"
echo "sha256 $(sha256sum "$DL/$f" | cut -d' ' -f1)  $f"
rm -rf "$SRCDIR/camel-lite-$VERSION" "$OUT"
mkdir -p "$SRCDIR/camel-lite-$VERSION" "$OUT/root"
tar -C "$SRCDIR/camel-lite-$VERSION" --strip-components=3 -xzf "$DL/$f" "tinymail-$COMMIT/libtinymail-camel/camel-lite"
cd "$SRCDIR/camel-lite-$VERSION"
patch -p1 < "$PROJ/apps/camel-lite/openssl3.patch" > "$OUT/patch.log"

export MAEMO_DEPS="$SSLDEP"
export PKG_CONFIG_SYSROOT_DIR="$SR"
export PKG_CONFIG_LIBDIR="$SR/usr/lib/pkgconfig"
export PKG_CONFIG_PATH=
# The standalone configure.ac lacks conditionals that the parent tinymail configure defines.
grep -q 'AM_CONDITIONAL(OS_WIN32' configure.ac || sed -i 's/^AC_OUTPUT/AM_CONDITIONAL(OS_WIN32, false)\nAC_OUTPUT/' configure.ac
autoreconf -fi > "$OUT/autoreconf.log" 2>&1 || { tail -20 "$OUT/autoreconf.log"; exit 1; }
# LDFLAGS --exclude-libs: do not export the static OpenSSL 3 symbols (the Modest process also loads the system libssl 0.9.8),
# but DO export the rest: libedataserver (e_*), bodystruct and the summary code are linked into libcamel-lite as static archives and
# libtinymail-camel / Modest use them from there (with --exclude-libs,ALL Modest died on undefined e_iconv_charset_name).
# CFLAGS: -fgnu89-inline and the compat header come from the wrapper / maemo-compat.h like in the other apps.
# ac_cv_*: configure tests that would have to run ARM programs.
# (Do not put comments between the variables below: they would end the command.)
CC="$PROJ/scripts/maemo-gcc" \
CFLAGS="-Os -g0 -include $PROJ/scripts/maemo-compat.h -DSYSTEM_MAIL_DIR=\\\"/var/mail\\\" -DSENDMAIL_PATH=\\\"/usr/sbin/sendmail\\\"" \
LDFLAGS="-Wl,--exclude-libs,libssl.a:libcrypto.a" \
LIBS="-ldl -lpthread" \
./configure --host=arm-linux-gnueabi --build="$(gcc -dumpmachine)" \
    --prefix=/usr --with-ssl=openssl --disable-static --enable-shared \
    --disable-gtk-doc --disable-nls \
    > "$OUT/configure.log" 2>&1 || { tail -30 "$OUT/configure.log"; exit 1; }
echo "== configured"
# iconv-detect.h is generated by a program that has to run on the target: run it under qemu-user (glibc 2.5 of the sysroot).
"$PROJ/scripts/maemo-gcc" -o iconv-detect iconv-detect.c
qemu-arm -L "$SR" ./iconv-detect 2> "$OUT/iconv-detect.log"
test -s iconv-detect.h
# SSL_LIBS: libgobject/libgthread/librt are not used by camel itself, but the original library had them as dependencies and
# libtinymail-camel relies on that (it calls g_thread_init without linking libgthread); -no-as-needed keeps them in NEEDED.
# libssl must come BEFORE libcrypto (static archives are searched in order); configure.ac has them reversed.
make -j"$(nproc)" SSL_LIBS="-lssl -lcrypto -Wl,--no-as-needed -lgobject-2.0 -lgthread-2.0 -lrt" > "$OUT/make.log" 2>&1 || { grep -E 'error|Error' "$OUT/make.log" | head -30; exit 1; }
make install DESTDIR="$OUT/root" >> "$OUT/make.log" 2>&1 || { tail -20 "$OUT/make.log"; exit 1; }
find "$OUT/root" -name '*.so*' -type f -exec arm-linux-gnueabi-strip --strip-unneeded {} +
rm -rf "$OUT/root/usr/include" "$OUT/root/usr/lib/pkgconfig" "$OUT/root"/usr/lib/*.la "$OUT/root"/usr/lib/camel-lite-1.2/camel-providers/*.la "$OUT/root/usr/share"
echo "== Check"
ls -l "$OUT/root/usr/lib" "$OUT/root/usr/lib/camel-lite-1.2/camel-providers"
# Test program (runs on the phone, make test): TLS connection through the new library.
mkdir -p "$OUT/root/opt/camel-lite3/bin"
INC="$(pkg-config --cflags glib-2.0 gobject-2.0 gthread-2.0 gmodule-2.0)"
# shellcheck disable=SC2086
"$PROJ/scripts/maemo-gcc" -Os $INC -I"$SRCDIR/camel-lite-$VERSION" -I"$SRCDIR/camel-lite-$VERSION/camel" -I"$SRCDIR/camel-lite-$VERSION/libedataserver" \
    -o "$OUT/root/opt/camel-lite3/bin/camel-tlstest" "$PROJ/apps/camel-lite/tlstest.c" \
    -L"$OUT/root/usr/lib" -lcamel-lite-1.2 -lgobject-2.0 -lgthread-2.0 -lglib-2.0
arm-linux-gnueabi-strip "$OUT/root/opt/camel-lite3/bin/camel-tlstest"
