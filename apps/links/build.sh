#!/bin/bash
# Cross-build links 2.x (text mode) for Maemo 5 with HTTPS over the static OpenSSL 3 of apps/openssl.
# Run INSIDE the Workshop (make -C apps/links build). Output: /project/build/out/links-$VERSION/root/opt/links/bin/links
# The stock browser of the phone cannot open modern HTTPS sites (TLS 1.0 only); this one speaks TLS 1.2/1.3.
set -euo pipefail

VERSION="${VERSION:-2.30}"
OPENSSL_VERSION="${OPENSSL_VERSION:-3.5.9}"
PROJ=/project
SR="$PROJ/sysroot"
DL="$PROJ/build/downloads"
SRCDIR="$PROJ/build/src"
OUT="$PROJ/build/out/links-$VERSION"
SSL="$PROJ/build/deps/openssl-$OPENSSL_VERSION"

[ -d "$SR/usr/include" ] || { echo "Missing sysroot, run: make sysroot"; exit 1; }
[ -s "$SSL/lib/libssl.a" ] || { echo "Missing $SSL, run: make openssl"; exit 1; }
mkdir -p "$DL" "$SRCDIR"
f="links-$VERSION.tar.gz"
[ -s "$DL/$f" ] || curl -fL --retry 3 -o "$DL/$f" "http://links.twibright.com/download/$f"
echo "sha256 $(sha256sum "$DL/$f" | cut -d' ' -f1)  $f"
rm -rf "$SRCDIR/links-$VERSION" "$OUT"
tar -C "$SRCDIR" -xzf "$DL/$f"
mkdir -p "$OUT/root"
cd "$SRCDIR/links-$VERSION"
# Text mode only (no X, no framebuffer). Compression libraries other than zlib are left out.
# MAEMO_DEPS puts the static OpenSSL 3 before the sysroot, so the old OpenSSL 0.9.8 of the SDK is never used.
export MAEMO_DEPS="$SSL"
# (The configure script is generated by an old autoconf: variables are passed in the environment, no --build.)
CC="$PROJ/scripts/maemo-gcc" CFLAGS="-Os -D_GNU_SOURCE -include $PROJ/scripts/maemo-compat.h" \
LIBS="-lpthread -ldl" \
./configure --host=arm-linux-gnueabi --prefix=/opt/links \
    --without-x --without-fb --without-directfb --without-svgalib --without-libjpeg --without-libtiff --without-librsvg \
    --without-openmp --without-brotli --without-zstd --without-lzma --without-bzip2 --without-gpm --without-ipv6 \
    --with-ssl="$SSL" \
    > "$OUT/configure.log" 2>&1 || { tail -30 "$OUT/configure.log"; exit 1; }
make -j"$(nproc)" > "$OUT/make.log" 2>&1 || { grep -E 'error|Error' "$OUT/make.log" | head -20; tail -15 "$OUT/make.log"; exit 1; }
mkdir -p "$OUT/root/opt/links/bin"
arm-linux-gnueabi-strip -o "$OUT/root/opt/links/bin/links" links
BIN="$OUT/root/opt/links/bin/links"
echo "== Check"
file "$BIN" | cut -c1-140
arm-linux-gnueabi-readelf -d "$BIN" | grep NEEDED
echo -n "Highest glibc symbol: "
arm-linux-gnueabi-objdump -T "$BIN" | grep -oE 'GLIBC_[0-9.]+' | sort -uV | tail -1
ls -l "$BIN"
